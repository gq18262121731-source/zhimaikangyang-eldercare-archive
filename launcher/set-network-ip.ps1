[CmdletBinding()]
param(
    [string]$InterfaceAlias = '',
    [string]$IpAddress = '',
    [string]$RobotIp = '192.168.123.161'
)

$ErrorActionPreference = 'Stop'
$Root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$ConfigDir = Join-Path $Root 'configs'
$ConfigPath = Join-Path $ConfigDir 'local.env'
New-Item -ItemType Directory -Force -Path $ConfigDir | Out-Null

function Test-IPv4([string]$Value) {
    $parsed = $null
    return [System.Net.IPAddress]::TryParse($Value, [ref]$parsed) -and $parsed.AddressFamily -eq [System.Net.Sockets.AddressFamily]::InterNetwork
}

if ($InterfaceAlias) {
    $configs = @(Get-NetIPConfiguration -InterfaceAlias $InterfaceAlias -ErrorAction Stop)
} else {
    $configs = @(Get-NetIPConfiguration -ErrorAction SilentlyContinue | Where-Object {
        $_.NetAdapter.Status -eq 'Up' -and $_.InterfaceAlias -match '(?i)wi-?fi|wlan|wireless|移动|热点'
    })
    if (-not $configs) {
        $configs = @(Get-NetIPConfiguration -ErrorAction SilentlyContinue | Where-Object { $_.NetAdapter.Status -eq 'Up' })
    }
}

$candidates = @($configs | ForEach-Object {
    $alias = $_.InterfaceAlias
    $_.IPv4Address | ForEach-Object {
        if ($_.IPAddress -and (Test-IPv4 $_.IPAddress)) {
            [pscustomobject]@{ Alias = $alias; Address = $_.IPAddress }
        }
    }
})

Write-Host 'Available network interfaces and IPv4 addresses:'
if ($candidates) { $candidates | Format-Table -AutoSize | Out-Host }
else { Write-Warning 'No Wi-Fi IPv4 was detected automatically. Use -IpAddress to set it manually.' }

if (-not $IpAddress) {
    $preferred = $candidates | Where-Object { $_.Alias -match '(?i)wi-?fi|wlan|wireless|移动|热点' } | Select-Object -First 1
    if (-not $preferred) { $preferred = $candidates | Select-Object -First 1 }
    if ($preferred) { $IpAddress = $preferred.Address }
}

if (-not (Test-IPv4 $IpAddress)) { throw "Invalid IPv4 address: $IpAddress" }
if (-not (Test-IPv4 $RobotIp)) { throw "Invalid Go2 Robot IPv4 address: $RobotIp" }

$lines = @(
    '# Generated by launcher/set-network-ip.ps1. Do not commit this file.',
    "HOST_IP=$IpAddress",
    "STATIC_PLATFORM_HOST=$IpAddress",
    'STATIC_PLATFORM_BACKEND_PORT=8080',
    'STATIC_PLATFORM_FRONTEND_PORT=5173',
    "VISION_SERVICE_HOST=$IpAddress",
    'VISION_SERVICE_PORT=8011',
    "VISION_SERVICE_PUBLIC_BASE_URL=http://$IpAddress`:8011",
    "MAIN_SYSTEM_BASE_URL=http://$IpAddress`:8080",
    "UNITREE_ROBOT_IP=$RobotIp",
    "UNITREE_NETWORK_INTERFACE=$InterfaceAlias"
)
Set-Content -LiteralPath $ConfigPath -Value $lines -Encoding UTF8
Write-Host "Wrote: $ConfigPath" -ForegroundColor Green
Write-Host "HOST_IP=$IpAddress"
Write-Host "UNITREE_ROBOT_IP=$RobotIp"
Write-Host 'This file is ignored by Git. Copy values into the relevant module .env when needed.'
